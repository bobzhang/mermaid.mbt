#!/usr/bin/env python3
"""Generate internal/css/cssom_property_names.mbt: the CSS properties Chrome knows.

A style sheet keeps a declaration of a property the browser knows (and
whose value is valid) and drops any other; the port needs the list to tell
the two apart. The names are read in the oracle's Chrome: every property of
a CSSStyleDeclaration and of the computed style, kept if `CSS.supports`
takes it with `inherit`.

Usage: python3 scripts/gen_css_properties.py
"""

import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import oracle  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "internal" / "css" / "cssom_property_names.mbt"

PROBE = """(() => {
  const names = new Set(Array.from(getComputedStyle(document.documentElement)));
  const style = document.createElement("div").style;
  for (const key in style) {
    if (typeof style[key] === "string") {
      names.add(key.includes("-") ? key
        : key.replace(/[A-Z]/g, (m) => "-" + m.toLowerCase()).replace(/^webkit-/, "-webkit-"));
    }
  }
  return [...names].filter((name) => CSS.supports(name, "inherit")).sort();
})()"""


def main():
    names = oracle.run([], {}, PROBE)[0]["value"]
    lines = ["// Generated by scripts/gen_css_properties.py from the oracle's Chrome; do not edit.", "",
             "///|", "/// The CSS properties Chrome knows.", "let property_names : Set[String] = Set::from_array(["]
    lines += [f"  {json.dumps(name)}," for name in names]
    lines += ["])", ""]
    OUT.write_text("\n".join(lines))
    print(f"{len(names)} properties written to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

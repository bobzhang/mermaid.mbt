#!/usr/bin/env python3
"""Turn one of mermaid's chevrotain parsers into a MoonBit grammar.

`scripts/extract_chevrotain.js` reads the token types, the lexer modes, the
grammar and the lookahead sequences of a parser out of the mermaid bundle;
this script writes them as a `@chevrotain.Grammar` value. Token patterns
that are JavaScript functions are listed in the generated file, to be
ported by hand and passed to `Grammar::tokenize`; so are the rules'
predicates (`GATE`), which the bundle does not describe: find them in the
parser's source and pass them to `Grammar::parse`. Building the model from
the syntax tree (the visitor) is always ported by hand.

Usage: python3 scripts/gen_chevrotain.py <diagram> <output.mbt> [--ident NAME]
"""

import argparse
import json
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent


def mbt_string(text):
    out = []
    for char in text:
        if char == "\\":
            out.append("\\\\")
        elif char == '"':
            out.append('\\"')
        elif char == "\n":
            out.append("\\n")
        elif char == "\r":
            out.append("\\r")
        elif char == "\t":
            out.append("\\t")
        elif char == "{":
            # Not an interpolation.
            out.append("\\u{7b}")
        elif ord(char) < 0x20 or ord(char) == 0x7F:
            out.append("\\u{%x}" % ord(char))
        else:
            out.append(char)
    return '"' + "".join(out) + '"'


def strings(names):
    return "[" + ", ".join(mbt_string(name) for name in names) + "]"


def token(entry):
    pattern = entry["pattern"]
    if pattern.get("custom"):
        kind = "Custom"
    elif pattern.get("regex") == "NOT_APPLICABLE" or pattern.get("none"):
        kind = "Category"
    elif "regex" in pattern:
        kind = "Regex(%s, %s)" % (mbt_string(pattern["regex"]), mbt_string(pattern["flags"]))
    else:
        raise SystemExit("token %s: unsupported pattern %r" % (entry["name"], pattern))
    arguments = [mbt_string(entry["name"]), kind]
    if entry.get("skipped"):
        arguments.append("skipped=true")
    if entry.get("longerAlt"):
        arguments.append("longer_alt=" + strings(entry["longerAlt"]))
    if entry.get("pushMode"):
        arguments.append("push_mode=" + mbt_string(entry["pushMode"]))
    if entry.get("popMode"):
        arguments.append("pop_mode=true")
    if entry.get("matchedBy"):
        arguments.append("matched_by=" + strings(entry["matchedBy"]))
    return "@chevrotain.TokenType::new(%s)" % ", ".join(arguments)


def paths(sequences):
    return "[" + ", ".join(strings(sequence) for sequence in sequences) + "]"


def production(item, lookahead):
    kind = item["type"]
    if kind == "Terminal":
        return "Terminal(%s)" % mbt_string(item["name"])
    if kind == "NonTerminal":
        return "NonTerminal(%s)" % mbt_string(item["name"])
    body = lambda definition: "[" + ", ".join(production(child, lookahead) for child in definition) + "]"
    key = "%s%d" % (kind, item["idx"])
    if kind in ("Option", "Repetition", "RepetitionMandatory"):
        return "%s(%d, %s, %s)" % (kind, item["idx"], paths(lookahead[key]), body(item["definition"]))
    if kind == "Alternation":
        alternatives = [
            "(%s, %s)" % (paths(sequences), body(alternative["definition"]))
            for sequences, alternative in zip(lookahead[key], item["definition"])
        ]
        return "Alternation(%d, [%s])" % (item["idx"], ", ".join(alternatives))
    raise SystemExit("unsupported production %s" % kind)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("diagram")
    parser.add_argument("output")
    parser.add_argument("--ident")
    args = parser.parse_args()
    data = json.loads(
        subprocess.run(
            ["node", str(ROOT / "scripts" / "extract_chevrotain.js"), args.diagram],
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    )
    ident = args.ident or "%s_grammar" % args.diagram
    custom = [entry["name"] for entry in data["tokens"] if entry["pattern"].get("custom")]
    lines = [
        "// Generated by scripts/gen_chevrotain.py from the chevrotain parser of",
        "// mermaid's %s diagram (%s). Do not edit by hand." % (args.diagram, data["chunk"]),
        "//",
        "// Lookahead: at most %d tokens." % data["maxLookahead"],
        "// Token types matched by a function, to be ported by hand:",
    ]
    lines += ["//   %s" % name for name in custom] or ["//   (none)"]
    lines += ["", "///|", "let %s : @chevrotain.Grammar = @chevrotain.Grammar::new(" % ident, "  tokens=["]
    lines += ["    %s," % token(entry) for entry in data["tokens"] if entry["name"] != "EOF"]
    lines += ["  ],", "  modes={"]
    lines += ["    %s: %s," % (mbt_string(mode), strings(names)) for mode, names in data["modes"].items()]
    lines += ["  },", "  default_mode=%s," % mbt_string(data["defaultMode"]), "  rules=["]
    for rule in data["grammar"]:
        lookahead = data["lookahead"][rule["name"]]
        body = ", ".join(production(item, lookahead) for item in rule["definition"])
        lines.append("    (%s, [%s])," % (mbt_string(rule["name"]), body))
    lines += ["  ],", ")", ""]
    output = pathlib.Path(args.output)
    output.write_text("\n".join(lines))
    subprocess.run(["moon", "fmt", str(output)], cwd=ROOT, check=False)


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Write the HTML named character references to `internal/dom/gen_entities.mbt`.

The table is the WHATWG one, as Python ships it (`html.entities.html5`):
2231 names, the 106 legacy ones also without their semicolon. Before
writing, every name is resolved by the reference browser's HTML parser and
compared with the table; the script refuses to write if any differs.

Usage: python3 scripts/gen_entities.py && moon fmt
"""

import html.entities
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import oracle  # noqa: E402

ROOT = oracle.ROOT

CHECK = """(() => {
  const names = %s;
  const out = {};
  const div = document.createElement('div');
  for (const name of names) {
    div.innerHTML = '&' + name;
    out[name] = div.textContent;
  }
  return out;
})()"""


def literal(text):
    return '"' + "".join(f"\\u{{{ord(c):x}}}" for c in text) + '"'


def main():
    table = html.entities.html5
    names = sorted(table)
    browser = oracle.run([], {}, CHECK % json.dumps(names))[0]["value"]
    wrong = [name for name in names if browser.get(name) != table[name]]
    if wrong:
        sys.exit(f"the browser resolves {len(wrong)} names differently: {wrong[:20]}")
    lines = [
        "// Generated by scripts/gen_entities.py from the WHATWG table, checked",
        "// against the reference browser. Do not edit by hand.",
        "",
        "///|",
        "/// Every named character reference the HTML parser knows, keyed by its",
        "/// name after the `&`: with its semicolon, and for the legacy names also",
        "/// without.",
        "let named_references : Map[String, String] = {",
        *[f'  "{name}": {literal(table[name])},' for name in names],
        "}",
        "",
    ]
    target = ROOT / "internal" / "dom" / "gen_entities.mbt"
    target.write_text("\n".join(lines))
    print(f"wrote {target.relative_to(ROOT)}: {len(names)} names")


if __name__ == "__main__":
    main()

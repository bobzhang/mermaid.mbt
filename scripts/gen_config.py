#!/usr/bin/env python3
"""Extract mermaid's default configuration from its JSON Schema.

Upstream builds `defaultConfig` by validating an empty object against
`packages/mermaid/src/schemas/config.schema.yaml` with ajv's `useDefaults`
(see `.build/jsonSchema.ts`). This script replays that and writes the result
as a MoonBit `Json` literal to `config/gen_defaults.mbt`.

The schema is YAML; it is converted with Ruby's bundled YAML library so the
script needs no third-party Python package.

Usage: python3 scripts/gen_config.py [path/to/mermaid] && moon fmt
"""

import copy
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

# The keys of the mermaid config that hold a diagram config, in the order
# `.build/jsonSchema.ts` lists them.
DIAGRAM_KEYS = [
    "flowchart", "swimlane", "agentflow", "sequence", "gantt", "journey",
    "class", "state", "er", "pie", "quadrantChart", "xyChart", "requirement",
    "mindmap", "ishikawa", "kanban", "timeline", "gitGraph", "c4", "sankey",
    "block", "packet", "treeView", "architecture", "eventmodeling", "radar",
    "usecase", "venn", "cynefin",
]


def load_schema(path):
    script = "require 'yaml'; require 'json'; puts JSON.generate(YAML.load_file(ARGV[0]))"
    out = subprocess.run(["ruby", "-e", script, str(path)], check=True, capture_output=True, text=True)
    return json.loads(out.stdout)


def resolve(schema, root):
    while "$ref" in schema:
        _, defs, name = schema["$ref"].split("/")
        schema = root[defs][name]
    return schema


def apply_defaults(schema, data, root):
    """Fill `data` with the `default` of every property it lacks."""
    if "$ref" in schema:
        apply_defaults(resolve(schema, root), data, root)
    for sub in schema.get("allOf", []):
        apply_defaults(sub, data, root)
    for name, prop in schema.get("properties", {}).items():
        if name not in data and "default" in prop:
            data[name] = copy.deepcopy(prop["default"])
        if isinstance(data.get(name), dict):
            apply_defaults(prop, data[name], root)


def generate_defaults(schema):
    config = {}
    base = schema["$defs"]["BaseDiagramConfig"]
    for key in DIAGRAM_KEYS:
        sub = resolve(schema["properties"][key], schema)
        config[key] = {}
        for required in sub.get("required", []):
            if required not in sub.get("properties", {}) and required in base["properties"]:
                config[key][required] = base["properties"][required]["default"]
        apply_defaults(sub, config[key], schema)
    apply_defaults(schema, config, schema)
    return config


def main():
    upstream = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / ".repos" / "mermaid"
    schema = load_schema(upstream / "packages" / "mermaid" / "src" / "schemas" / "config.schema.yaml")
    defaults = json.dumps(generate_defaults(schema), indent=2, ensure_ascii=False)
    target = ROOT / "config" / "gen_defaults.mbt"
    target.write_text(
        "// Generated by scripts/gen_config.py from mermaid's config.schema.yaml.\n"
        "// Do not edit by hand.\n\n"
        "///|\n"
        "/// The defaults declared by mermaid's configuration JSON Schema.\n"
        "fn schema_defaults() -> Json {\n"
        + "\n".join("  " + line for line in defaults.splitlines())
        + "\n}\n"
    )
    print(f"wrote {target.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

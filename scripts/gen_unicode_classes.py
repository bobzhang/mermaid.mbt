"""Write internal/rendering/unicode_classes.mbt: the code point ranges of the
Unicode property classes marked's emphasis rules use, as the oracle's Chrome
sees them (`/[\\p{P}\\p{S}]/u` and `/[\\p{L}\\p{N}]/u`).

Usage: python3 scripts/gen_unicode_classes.py
"""
import json, pathlib, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
JS = r"""(() => {
  const ranges = (re) => {
    const out = []; let start = -1;
    for (let c = 0; c <= 0x110000; c++) {
      const inside = c < 0x110000 && !(c >= 0xd800 && c < 0xe000) && re.test(String.fromCodePoint(c));
      if (inside && start < 0) start = c;
      if (!inside && start >= 0) { out.push([start, c - 1]); start = -1; }
    }
    return out;
  };
  return { ps: ranges(/[\p{P}\p{S}]/u), ln: ranges(/[\p{L}\p{N}]/u), ua: navigator.userAgent };
})()"""
out = subprocess.run([sys.executable, str(ROOT / 'scripts/oracle.py'), '--eval', JS],
                     capture_output=True, text=True, check=True).stdout
data = json.loads(out)


def table(name, doc, ranges):
    items = [f'(0x{a:x}, 0x{b:x})' for a, b in ranges]
    lines = ['  ' + ', '.join(items[i:i + 6]) + ',' for i in range(0, len(items), 6)]
    return f'///|\n/// {doc}\nlet {name} : Array[(Int, Int)] = [\n' + '\n'.join(lines) + '\n]\n'


chrome = data['ua'].split('Chrome/')[1].split(' ')[0]
text = (f'// Generated by scripts/gen_unicode_classes.py (Chrome {chrome}); do not edit.\n\n'
        + table('punctuation_or_symbol', 'The code points of `/[\\p{P}\\p{S}]/u`, as sorted ranges.', data['ps'])
        + '\n'
        + table('letter_or_number', 'The code points of `/[\\p{L}\\p{N}]/u`, as sorted ranges.', data['ln']))
(ROOT / 'internal/rendering/unicode_classes.mbt').write_text(text)

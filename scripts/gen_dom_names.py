#!/usr/bin/env python3
"""List the property names that DOMPurify refuses as `id` or `name` values.

mermaid's output goes through DOMPurify with `SANITIZE_DOM` on, which
drops an `id` or `name` attribute whose value is a property of `document`
or of a `<form>` element (so markup cannot shadow them: "DOM clobbering").
A participant called `title` or `links` therefore loses its `name`
attribute. This script asks the reference browser for those names and
writes them to `internal/dom/gen_clobber.mbt`.

Usage: python3 scripts/gen_dom_names.py && moon fmt
"""

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import oracle  # noqa: E402

ROOT = oracle.ROOT

NAMES = """(() => {
  const names = new Set();
  const form = document.createElement('form');
  for (const start of [document, form]) {
    for (let o = start; o; o = Object.getPrototypeOf(o)) {
      for (const key of Object.getOwnPropertyNames(o)) names.add(key);
    }
  }
  return [...names].filter((key) => key in document || key in form).sort();
})()"""


def main():
    names = oracle.run([], {}, NAMES)[0]["value"]
    rows, row = [], "   "
    for name in names:
        piece = f' "{name}",'
        if len(row) + len(piece) > 92:
            rows.append(row)
            row = "   "
        row += piece
    rows.append(row)
    lines = [
        "// Generated by scripts/gen_dom_names.py from the reference browser.",
        "// Do not edit by hand.",
        "",
        "///|",
        "/// Every property name of `document` and of a `<form>` element.",
        "let clobbering_names : Array[String] = [",
        *rows,
        "]",
        "",
    ]
    target = ROOT / "internal" / "dom" / "gen_clobber.mbt"
    target.write_text("\n".join(lines))
    print(f"wrote {target.relative_to(ROOT)}: {len(names)} names")


if __name__ == "__main__":
    main()
